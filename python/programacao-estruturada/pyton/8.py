# ATIVIDADE 

num1 = int(input("Digite o primeiro valor: ")) 
num2 = int(input("Digite o segundo valor: "))

soma=num1+num2 # soma
sub=num1-num2 # subtração
mult=num1*num2 # multiplicação
div=num1/num2 # divisão

print(f"{num1} mais {num2} é igual a {soma}") # soma
print(f"{num1} menos {num2} é igual a {sub}") # subtração
print(f"O produto de {num1} e {num2} é igual a {mult}") # multiplicação
print(f"{num1} dividido por {num2} é igual a {div}") # divisão
