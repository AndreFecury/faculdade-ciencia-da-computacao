    sub = subtrair (num1, num2)
    mult = multiplicar (num1, num2)
    div = dividir (num1, num2)
    
    print(f"A soma é {soma}")
    print(f"A subtração é {sub}")
    print(f"o produto de é {mult}")
    print(f"A divisão é {div}")
    
    
    
